#!/bin/bash
set -e

# Setup the Quartus project used to compile the bitstream for the
# memory-to-memory Agilex 5 SoC example design.
#
# This script expects two arguments:
#   - The architecture IP name (e.g., AGX7_Performance_AGX7)
#   - The path to the directory containing the DLA IP RTL files

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <arch_ip_name> <dla_ip_dir>"
  exit -1
fi

ARCH_IP_NAME=$1
DLA_IP_DIR=$2

# VDS always writes its systems to "src/vds" of the Quartus project directory,
# and Visual Designer Studio only finds them there when "top" is opened in the
# GUI, so the systems are built directly in this directory.
for stale_dir in src gen dni qdb; do
  if [ -d $stale_dir ]; then
    echo "INFO: Cleaning up old $stale_dir"
    rm -Rf $stale_dir
  fi
done

# Clone DLA IPX and adjust path relative to this project. Quartus reads .ipx
# files in the project directory automatically, which is how the VDS build
# resolves the DLA IP.
cp $DLA_IP_DIR/altera.ipx .
sed -i 's+file="+file="'$(basename $DLA_IP_DIR)'/+g' altera.ipx

# Stage the pre-generated HPS EMIF IP. The VDS system.tcl imports it as a
# standalone file from "$proj_dir/src/ip", where $proj_dir resolves to this
# directory, so the file must exist before system.tcl runs.
mkdir -p src/ip
cp ip/hps_emif_io96b_hps_0.ip src/ip/

# top.qsf sources this file unconditionally, including on the Quartus run that
# builds the VDS systems, so it has to exist beforehand. build_project.sh
# overwrites it with the real assignments once the systems have been built.
echo "# Placeholder - regenerated by build_project.sh." > vds_files.tcl

# Select the DLA architecture based on the cmd-line configuration. The VDS
# export writes the altera_ai_ip cell as a "-vlnv" instantiation and only
# records parameters that differ from the component defaults. Inject ARCH_OPTION
# into the cell's VDS "-properties", which is how VDS carries IP parameter values.
sed -i -E "s#\} (-vlnv altera.com:ip:altera_ai_ip:[0-9.]* altera_ai_ip_0)#parameters:ARCH_OPTION {$ARCH_IP_NAME} } \1#" system.tcl
