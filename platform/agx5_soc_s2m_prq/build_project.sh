#!/bin/bash
set -e

# Build the bitstream and NIOS software image for the streaming-to-memory
# Agilex 5 SoC example design.  This script takes in no arguments and must run
# after calling 'setup_project.sh'.

# Build the VDS systems.
#
# system.tcl uses "load_package vds" and the vds:: Tcl API, which is only
# available through quartus_sh, and the script calls get_project_directory, so
# a Quartus project must be open before it is sourced. VDS always writes its
# systems to "src/vds" of the open project's directory and Visual Designer
# Studio only finds them there, so the "top" project itself is opened here
# rather than a scratch project in a subdirectory. VDS records VDS_FILE/
# VDS_IP_FILE assignments for the systems it saves, but those are incomplete
# (see below) and are regenerated in full afterwards, so top.qsf is restored
# from a copy once the systems are built. -dont_export_assignments is not
# enough on its own: VDS writes the settings file itself.
#
# VDS GUI-backed operations (create_system) require an X display even when
# scripted, so Xvfb is started and pointed to directly here. This requires
# Xvfb to be installed (package "xvfb" on Ubuntu, "xorg-x11-server-Xvfb" on
# RHEL).
if ! command -v Xvfb >/dev/null 2>&1; then
    echo "Error: Xvfb not found. Please install it (package \"xvfb\" on Ubuntu, \"xorg-x11-server-Xvfb\" on RHEL)." >&2
    exit 1
fi

cp top.qsf top.qsf.orig
cat > build_system.tcl <<'TCL_EOF'
project_open top
# system.tcl itself gives no progress feedback while it builds each system
# (a multi-minute, silent step), so every mutating vds:: command (create_
# system/create_cell/connect_net/etc., but not query commands like get_*/
# list_*/report_*/is_*) is traced to print as it runs. load_package vds is
# called early here (it's a no-op if system.tcl calls it again) so the vds::
# commands exist to trace before system.tcl is sourced.
load_package vds
proc log_vds_call {commandString op} { puts "VDS: $commandString" }
foreach vds_cmd [info commands ::vds::*] {
    set vds_cmd_name [namespace tail $vds_cmd]
    if {[regexp {^(get|list|report|is)_} $vds_cmd_name]} continue
    trace add execution $vds_cmd enter log_vds_call
}
source system.tcl
project_close -dont_export_assignments
TCL_EOF

(
    display=":$$"
    Xvfb "$display" -screen 0 1024x768x24 -nolisten tcp &
    xvfb_pid=$!
    trap 'kill $xvfb_pid 2>/dev/null' EXIT
    for i in 1 2 3 4 5; do [ -e "/tmp/.X11-unix/X${display#:}" ] && break; sleep 1; done
    DISPLAY="$display" quartus_sh -t build_system.tcl
)

mv top.qsf.orig top.qsf
rm -f top.qsf.backup

# Record the VDS assignments for the "top" project in vds_files.tcl, which
# top.qsf sources. This step doesn't touch the vds:: package (no X display
# needed), so it runs in a plain quartus_sh with no Xvfb wrapping.
#
# Enumerate the generated VDS output directly from the filesystem rather than
# letting system.tcl record the assignments: it does not reliably record a
# VDS_IP_FILE assignment for every child IP (the emif subsystem's children, for
# example, are omitted), which leaves those IPs out of top-level generation and
# produces "undefined entity" synthesis errors. Each system directory holds
# "<system>.vds" plus an "ip" subdirectory of child IPs, so the assignments can
# be reconstructed deterministically.
#
# The compile-time IP search path must cover both the custom IP _hw.tcl files
# (under ip) and the DLA IP, which is registered through altera.ipx. The DLA IP
# directory is recorded in that .ipx relative to this directory, so derive it
# here rather than hard-coding the name.
cat > write_vds_files.tcl <<'TCL_EOF'
set fp [open altera.ipx r]
set ipx_data [read $fp]
close $fp
regexp {file="([^/]+)} $ipx_data -> dla_ip_dir

set fp [open vds_files.tcl w]
puts $fp "# Auto-generated by build_project.sh - do not edit."
puts $fp "set_global_assignment -name IP_SEARCH_PATHS \"ip/**/*,${dla_ip_dir}/**/*\""
foreach vds_file [glob -nocomplain src/vds/*/*.vds] {
	set sysdir [file dirname $vds_file]
	set sys [file tail $sysdir]
	puts $fp "set_global_assignment -name VDS_FILE $vds_file -tag \"vds::$sys\""
	foreach ip_file [glob -nocomplain $sysdir/ip/*.ip] {
		puts $fp "set_global_assignment -name VDS_IP_FILE $ip_file -tag \"vds::$sys\""
	}
}
close $fp
TCL_EOF
quartus_sh -t write_vds_files.tcl

# Create the HEX image. niosv-bsp's --system option is documented to take
# "the system file" (not specifically a .qsys file), so it is pointed here at
# the "dla" VDS system instead of the old qsys-generated dla.qsys.
./build_stream_controller.sh top.qpf src/vds/dla/dla.vds stream_controller.hex

if [ ! -e stream_controller.hex ]; then
  echo "FATAL : Failed to create NIOS software image"
  exit 1
fi

# Compile the Quartus project
quartus_sh --flow compile top 2>&1 | tee quartus_sh.log

# Extract the QoR report
quartus_sh -t dla_parse_report.tcl \
    -project top \
    -ip-clock "system_inst|dla_pll|dla_pll_clk_dla" \
    -platform-clock "MAIN_CLOCK"

