#!/bin/bash
set -e

# Setup the Quartus project used to compile the bitstream for the
# hostless Agilex 5E Modular DDR-Free LT-DDRWB example design (VDS board + emif).
#
# This script expects two arguments:
#   - The architecture IP name (e.g., 16x16_..._AGX5)
#   - The path to the directory containing the DLA IP RTL files
#
# DLA IP is wired through dla_platform.qsf / the platform wrapper, not as a
# VDS cell in system.tcl. AXI stream width is injected into system.tcl the
# same way the PD flow patched board.tcl (st_adapter outDataWidth).

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <arch_ip_name> <dla_ip_dir>"
  exit -1
fi

ARCH_IP_NAME=$1
DLA_IP_DIR=$2

echo "INFO: Preparing agx5e_modular_ddrfree_ltddrwb VDS project for architecture ${ARCH_IP_NAME}"

# Read AXI istream width from the generated DLA IP params (same as PD setup).
DMA_PARAM="$DLA_IP_DIR/altera_ai_ip/verilog/$ARCH_IP_NAME/dla_dma_param.svh"
if [ ! -f "$DMA_PARAM" ]; then
  echo "ERROR: DLA IP parameter file not found: $DMA_PARAM"
  exit -1
fi

AXI_ISTREAM_DATA_WIDTH=$(grep -oP 'localparam int AXI_ISTREAM_DATA_WIDTH = \K\d+' "$DMA_PARAM")
if [ -z "$AXI_ISTREAM_DATA_WIDTH" ]; then
  echo "ERROR: Unable to determine AXI_ISTREAM_DATA_WIDTH from $DMA_PARAM"
  exit -1
fi
echo "INFO: AXI_ISTREAM_DATA_WIDTH = $AXI_ISTREAM_DATA_WIDTH"

# Inject width into system.tcl (placeholder matches PD board.tcl INPUT_DATA_WIDTH).
if [ ! -f system.tcl ]; then
  echo "ERROR: system.tcl not found in $(pwd)"
  exit -1
fi
sed -i "s/parameters:outDataWidth {INPUT_DATA_WIDTH}/parameters:outDataWidth {${AXI_ISTREAM_DATA_WIDTH}}/" system.tcl
if ! grep -q "parameters:outDataWidth {${AXI_ISTREAM_DATA_WIDTH}}" system.tcl; then
  echo "ERROR: Failed to update outDataWidth in system.tcl"
  exit -1
fi
echo "INFO: Updated st_adapter_0 outDataWidth in system.tcl to $AXI_ISTREAM_DATA_WIDTH"

# VDS always writes its systems to "src/vds" of the Quartus project directory,
# and Visual Designer Studio only finds them there when "top" is opened in the
# GUI, so the systems are built directly in this directory.
for stale_dir in src gen dni qdb; do
  if [ -d $stale_dir ]; then
    echo "INFO: Cleaning up old $stale_dir"
    rm -Rf $stale_dir
  fi
done

# Clone DLA IPX and adjust path relative to this project. Quartus reads .ipx
# files in the project directory automatically. build_project.sh also derives
# the DLA IP search path from this file when writing vds_files.tcl.
cp $DLA_IP_DIR/altera.ipx .
sed -i 's+file="+file="'$(basename $DLA_IP_DIR)'/+g' altera.ipx

# Stage the preconfigured CSR AXI bridge. system.tcl imports four instances
# via "vds::create_cell -type ip" from src/ip.
mkdir -p src/ip
cp ip/dla_csr_axi_bridge.ip src/ip/

# top.qsf sources this file unconditionally, including on the Quartus run that
# builds the VDS systems, so it has to exist beforehand. build_project.sh
# overwrites it with the real assignments once the systems have been built.
echo "# Placeholder - regenerated by build_project.sh." > vds_files.tcl
